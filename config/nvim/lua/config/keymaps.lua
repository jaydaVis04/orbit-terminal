local map = vim.keymap.set
map("n", "<Esc>", "<cmd>nohlsearch<cr>", { desc = "Clear search highlight" })
map("n", "<C-s>", "<cmd>write<cr>", { desc = "Save file" })
map("i", "<C-s>", "<Esc><cmd>write<cr>a", { desc = "Save file" })
map("n", "<leader>w", "<cmd>write<cr>", { desc = "Save file" })
map("n", "<leader>q", "<cmd>confirm quit<cr>", { desc = "Quit window" })
map("n", "<C-h>", "<C-w>h", { desc = "Window left" })
map("n", "<C-j>", "<C-w>j", { desc = "Window below" })
map("n", "<C-k>", "<C-w>k", { desc = "Window above" })
map("n", "<C-l>", "<C-w>l", { desc = "Window right" })
map("n", "<leader>|", "<cmd>vsplit<cr>", { desc = "Split vertically" })
map("n", "<leader>-", "<cmd>split<cr>", { desc = "Split horizontally" })
map("n", "<S-h>", "<cmd>bprevious<cr>", { desc = "Previous buffer" })
map("n", "<S-l>", "<cmd>bnext<cr>", { desc = "Next buffer" })
map("n", "<leader>bd", function() require("mini.bufremove").delete(0, false) end, { desc = "Close buffer" })
map("v", "<", "<gv", { desc = "Indent left" })
map("v", ">", ">gv", { desc = "Indent right" })
map("n", "<leader>ud", function() vim.diagnostic.enable(not vim.diagnostic.is_enabled()) end, { desc = "Toggle diagnostics" })
map("n", "<leader>uw", function() vim.wo.wrap = not vim.wo.wrap end, { desc = "Toggle word wrap" })
map("n", "<leader>un", function() vim.wo.relativenumber = not vim.wo.relativenumber end, { desc = "Toggle relative numbers" })
map("n", "<leader>xl", vim.diagnostic.setloclist, { desc = "Buffer diagnostics" })
map("n", "<leader>xx", vim.diagnostic.open_float, { desc = "Line diagnostics" })
map("n", "<leader>cn", "<cmd>edit ~/.config/nvim/init.lua<cr>", { desc = "Edit Neovim config" })
map("n", "<leader>ch", "<cmd>edit ~/.config/TERMINAL-KEYS.md<cr>", { desc = "Open setup key guide" })
map("t", "<C-\\><Esc>", "<C-\\><C-n>", { desc = "Leave terminal mode" })
