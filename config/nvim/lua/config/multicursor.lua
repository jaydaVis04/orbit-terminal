local mc = require("multicursor-nvim")
mc.setup()
local function map(modes, key, fn, desc) vim.keymap.set(modes, key, fn, { desc = desc }) end
map({ "n", "x" }, "<C-n>", function() mc.matchAddCursor(1) end, "Add cursor at next match")
map({ "n", "x" }, "<leader>mn", function() mc.matchAddCursor(1) end, "Add next match")
map({ "n", "x" }, "<leader>mN", function() mc.matchAddCursor(-1) end, "Add previous match")
map({ "n", "x" }, "<leader>ms", function() mc.matchSkipCursor(1) end, "Skip next match")
map({ "n", "x" }, "<leader>ma", mc.matchAllAddCursors, "Add all matches")
map({ "n", "x" }, "<M-S-Up>", function() mc.lineAddCursor(-1) end, "Add cursor above")
map({ "n", "x" }, "<M-S-Down>", function() mc.lineAddCursor(1) end, "Add cursor below")
-- Terminal-independent alternatives to Option-Shift-arrows.
map({ "n", "x" }, "<leader>mk", function() mc.lineAddCursor(-1) end, "Add cursor above")
map({ "n", "x" }, "<leader>mj", function() mc.lineAddCursor(1) end, "Add cursor below")
map({ "n", "x" }, "<leader>mt", mc.toggleCursor, "Toggle cursor enabled")
map("n", "<leader>mr", mc.restoreCursors, "Restore cursors")
map("n", "<leader>mc", mc.clearCursors, "Clear extra cursors")
map("n", "<leader>m=", mc.alignCursors, "Align cursors")
map({ "n", "x" }, "ga", mc.addCursorOperator, "Add cursors to motion/selection")
map("n", "<C-LeftMouse>", mc.handleMouse, "Add mouse cursor")
map("n", "<C-LeftDrag>", mc.handleMouseDrag, "Drag cursors")
map("n", "<C-LeftRelease>", mc.handleMouseRelease, "Release cursors")
mc.addKeymapLayer(function(set)
  set({ "n", "x" }, "<Left>", mc.prevCursor)
  set({ "n", "x" }, "<Right>", mc.nextCursor)
  set({ "n", "x" }, "<leader>mx", mc.deleteCursor)
  set("n", "<Esc>", function()
    if not mc.cursorsEnabled() then mc.enableCursors() else mc.clearCursors() end
    vim.cmd.nohlsearch()
  end)
end)
